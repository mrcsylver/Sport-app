#!/usr/bin/env python3
"""Write supabase/shop.sql from schema.sql.

THE SHOP HAD NO LOCK ON IT. `set_banner`, `set_avatar`, `set_name_color` and
`set_league_badge` took any string that fit the column, so the first cosmetic
anybody charged for would have been free to anybody willing to call the
function by hand — and "all free while we build it out" was the only thing
holding that together.

shop_items is the catalogue the setters now check against: one row per
cosmetic the app can draw, generated from the client's own arrays, every one
of them free. entitlements is what somebody owns beyond the free rows. A
payment provider is the next writer of that table; until then the control room
grants by hand.

It also opens the slot the catalogue exists for: uploaded designs, with their
own `frame` kind drawn around an avatar, and the Storage bucket to keep them
in -- admin-write, CDN-read, and no SVG anywhere near it.

Usage:  python3 tools/build_shop_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "shop.sql")

# Create-only: nothing already live changes shape, so there is nothing to drop
# first. The four setters are replaced in place, which is why they are here.
OBJECTS = ["may_wear", "check_wear", "shop_catalogue", "set_frame",
           "league_frames",
           "set_avatar", "set_banner", "set_name_color", "set_league_badge",
           "admin_shop_items", "admin_save_shop_item",
           "admin_retire_shop_item", "admin_grant_item", "admin_revoke_item"]

WANTED = tuple(OBJECTS)

HEAD = """-- ======================================================================
--  IRON LEAGUE — the shop gets a lock on it
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. NOTHING LOGGED IS TOUCHED, no points
--  are rewritten, and nobody loses a cosmetic they are already wearing.
--
--  GENERATED by tools/build_shop_migration.py, which lifts every function
--  below out of supabase/schema.sql. Edit there and re-run it, never here.
--
--  WHY: THE SHOP HAD NO LOCK ON IT
--  set_banner, set_avatar, set_name_color and set_league_badge took any
--  string that fit the column. Length was the only check. So the first item
--  anybody charged for would have been free to anybody willing to call the
--  function by hand, and "everything here is free while we build it out" was
--  doing the work a paywall is supposed to do.
--
--  shop_items is the catalogue those four now check against: one row per
--  cosmetic the app can draw -- 198 of them -- generated from the client's
--  own arrays by tools/build_shop.py so a key cannot go missing and leave
--  somebody's banner refusing to save. Every row it seeds is FREE, so
--  applying this file changes nothing anybody can see.
--
--  entitlements is what somebody owns beyond the free rows. A payment
--  provider is the next writer of it; until then admin_grant_item() hands
--  things out by name, which stays useful afterwards -- a prize, an apology,
--  a founder's gift.
--
--  AND THE SLOT THE CATALOGUE EXISTS FOR: UPLOADED DESIGNS
--  profiles.frame is a ring drawn around an avatar, on every row of every
--  board. It is the one cosmetic slot that is uploaded artwork rather than
--  CSS, because a ring is small, sits on one element, and is where a moving
--  design is worth its bytes.
--
--  The `designs` bucket holds the files. Reading is public and goes through
--  the CDN, which is the only way the bandwidth works on a free project.
--  Writing is admin-only, checked by the same is_admin() flag as everything
--  else. allowed_mime_types is the real gate, and SVG is deliberately NOT on
--  it: an SVG can carry script and the app inlines emblem SVGs, so one
--  uploaded here would be a paste away from running. PNG, WebP and Lottie
--  JSON cover everything the shop needs, animation included.
-- ======================================================================
begin;
set local check_function_bodies = off;

-- ------------------------------------------------- the catalogue ---
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]

    parts.append(lift(schema, "table", "shop_items"))
    parts.append("create unique index if not exists shop_items_kind_item\n"
                 "  on public.shop_items (kind, item);\n")
    parts.append(lift(schema, "table", "entitlements"))
    parts.append("create index if not exists entitlements_profile\n"
                 "  on public.entitlements (profile_id);\n")

    parts.append("-- -------------------------------------------- the ring slot ---")
    parts.append("alter table public.profiles add column if not exists frame text;")
    parts.append("alter table public.profiles drop constraint if exists "
                 "profiles_frame_check;")
    parts.append("alter table public.profiles add constraint profiles_frame_check\n"
                 "  check (frame is null or char_length(frame) between 1 and 40);\n")

    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")

    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, WANTED))

    parts.append("\n-- ------------------------------------ the seed, and the bucket ---")
    parts.append(seed(schema))
    parts.append(bucket(schema))
    parts.append(TAIL)

    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


def between(schema, begin, end, what):
    """The generated block schema.sql keeps between two markers."""
    try:
        i = schema.index(begin)
        j = schema.index(end, i) + len(end)
    except ValueError:
        raise SystemExit("cannot find the %s block in schema.sql" % what)
    return schema[i:j]


def seed(schema):
    # The seed is an upsert already, which is what makes it safe here.
    return between(schema, "-- SHOP BEGIN", "-- SHOP END", "catalogue seed")


def bucket(schema):
    i = schema.index("do $do$\nbegin\n  if exists (select 1 from information_schema.tables")
    j = schema.index("end $do$;", i) + len("end $do$;")
    return "\n" + schema[i:j]


if __name__ == "__main__":
    main()
