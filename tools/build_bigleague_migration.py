#!/usr/bin/env python3
"""Write supabase/big-league.sql from schema.sql.

A league held 36 people, as a hard ceiling in a CHECK constraint, and 36 is
the number the five divisions come to. That is the right size for a group of
friends and the wrong one for a poster on a gym wall: the 37th person to scan
it is turned away at the door, and they do not come back.

The creator picks it now, 2 to 100, at creation and afterwards. It can go up
at any time and never below the people already in -- the capacity trigger
only runs on the way IN, so shrinking would leave a league reading 40/30 and
refusing the 41st with no way to explain itself.

BOTH FUNCTIONS CHANGE SHAPE, and that is the awkward part. PostgREST resolves
a call by argument NAME, so a defaulted new parameter does not keep an old
app working -- it makes every old call match two functions at once:

    function public.create_league(p_name => ...) is not unique

So exactly one of each may be visible, and this file moves the old pair into
the `retired` schema in the same transaction as it creates the new: PostgREST
does not look there, the move is reversible with one ALTER, and -- unlike a
DROP -- the migration channel this project applies through will run it.

Usage:  python3 tools/build_bigleague_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "big-league.sql")

OBJECTS = ["create_league", "set_league_settings"]

HEAD = """-- ======================================================================
--  IRON LEAGUE — a league can hold up to 100
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. NOTHING LOGGED IS TOUCHED, no points
--  move, and every existing league keeps the size it already has.
--
--  GENERATED by tools/build_bigleague_migration.py, which lifts both
--  functions below out of supabase/schema.sql. Edit there and re-run it,
--  never here.
--
--  WHY
--  36 was a hard ceiling in a CHECK constraint, and 36 is the number the five
--  divisions come to. That is the right size for a group of friends and the
--  wrong one for a poster on a gym wall: the 37th person to scan the QR code
--  is turned away at the door, and they do not come back.
--
--  WHAT CHANGES
--  · the ceiling goes from 36 to 100. The DEFAULT is still 36, so a league
--    created without an opinion is the league it has always been.
--  · create_league() takes p_size.
--  · set_league_settings() takes p_max_members, which may be left null to
--    leave the size alone.
--
--  It can go UP at any time and never below the people already in. The
--  capacity trigger only runs on the way in, so shrinking would remove
--  nobody — it would just leave a league reading 40/30 and refusing the 41st
--  with no way to explain itself. That raises LEAGUE_SHRINK instead.
--
--  THE PART THAT IS NOT OBVIOUS
--  A defaulted new parameter looks like it keeps an app that has not updated
--  working. It does not. PostgREST resolves a call by argument NAME, and an
--  old app's call matches both the old function and the new one, so Postgres
--  refuses it:
--
--      function public.create_league(p_name => ...) is not unique
--
--  So exactly one of each may be visible. This file moves the old pair into
--  the `retired` schema rather than dropping them: PostgREST does not look
--  there, the move is reversible, and the migration channel this project
--  applies through will actually run it. Both happen in one transaction, so
--  there is no instant where both are callable and none where neither is.
--
--  ORDER OF DEPLOY: this file first, the app second. In between, an app that
--  has not updated calls create_league with p_name only and gets a 36-seat
--  league, which is exactly what it asked for.
--
--  The divisions are client-side, so they are not in here, but they move with
--  it: past 36 rows the bottom three grow in the proportion they already have
--  and the top two never do. A Royal Guard of six is not a Royal Guard.
-- ======================================================================
begin;
set local check_function_bodies = off;

-- ------------------------------------------- somewhere to park the old ---
create schema if not exists retired;
revoke all on schema retired from public;

-- ------------------------------------------------------- the ceiling ---
-- A CHECK cannot be widened in place; it is dropped and re-added. Nothing is
-- re-validated downward, so no existing row can fail the new one -- every
-- value that passed "between 2 and 36" passes "between 2 and 100".
alter table public.leagues drop constraint if exists leagues_max_members_check;
alter table public.leagues add constraint leagues_max_members_check
  check (max_members between 2 and 100);

-- --------------------------------- and the old shapes of both, retired ---
do $mv$
declare r record; alias text;
begin
  for r in
    select p.oid as id, p.oid::regprocedure as sig, p.proname as nom
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and (p.proname, pg_get_function_identity_arguments(p.oid)) in
          (('create_league', 'p_name text'),
           ('set_league_settings',
            'p_league uuid, p_rest_dow integer[], p_season_weeks integer, '
            || 'p_catchup_dow integer, p_season_break integer'))
  loop
    begin
      execute format('alter function %s set schema retired', r.sig);
    exception when duplicate_function then
      -- An older generated migration re-created the shape this file retires
      -- and a copy is already parked, so the obvious name is taken. Park this
      -- one under its own rather than leave it visible: a visible twin is
      -- what makes every call from an app that has not updated ambiguous.
      alias := r.nom || '_' || r.id::text;
      execute format('alter function %s rename to %I', r.sig, alias);
      execute format('alter function public.%I(%s) set schema retired',
                     alias, pg_get_function_identity_arguments(r.id));
    end;
    raise notice 'retired %', r.sig;
  end loop;
end $mv$;
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, tuple(OBJECTS)))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
