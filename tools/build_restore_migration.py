#!/usr/bin/env python3
"""Write supabase/restore-throttle.sql from schema.sql.

A restore code is 32 bits and hands over a whole account. That was fine while
the only way to try one was to type it into a phone. It stops being fine the
moment the app is advertised on a wall, because then the people trying codes
include ones running a script.

restore_profile() now refuses a caller after ten failures in an hour -- the
right code included, so a script that eventually lands on one cannot spend it.

THE SHAPE CHANGE, and why there has to be one.

The obvious way to write this is: record the failure, then
`raise exception 'BAD_CODE'` as before. It does not work. PostgREST runs one
call as one transaction, so the raise rolls back the row that records the
failure. The count stays at zero, the lock never closes, and nothing about
the app looks any different -- the caller sees the same refusal either way.
supabase/test/guessing.sql section 2 is the check that caught it.

So a code that matches nothing is answered with zero rows instead, which
means the return type goes from `public.profiles` to `setof public.profiles`.
`create or replace` cannot change a return type, and the migration channel
this project applies through will not run a DROP, so the old version is moved
into the `retired` schema in the same transaction instead -- the same trick
season-stats.sql used, and reversible with one ALTER.

Usage:  python3 tools/build_restore_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "restore-throttle.sql")

HEAD = """-- ======================================================================
--  IRON LEAGUE — ten guesses an hour at a restore code, and no more
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. NOTHING LOGGED IS TOUCHED, no points
--  move, and no profile changes hands.
--
--  GENERATED by tools/build_restore_migration.py, which lifts the table and
--  the function below out of supabase/schema.sql. Edit there and re-run it,
--  never here.
--
--  WHY
--  A restore code is 8 hex characters: 32 bits, and whoever has one owns the
--  account it belongs to — its history, its badges, every week it won. That
--  was a sensible trade while the only way to try a code was to type it into
--  a phone, and everybody with the app was a friend. It stops being one the
--  day the app is advertised on a wall, because then the people trying codes
--  include ones running a script, and 32 bits is a number a script walks.
--
--  WHAT CHANGES
--  Ten failures in a rolling hour and that caller stops being answered at
--  all — the RIGHT code included, which is the only part that matters: a
--  script that finally lands on a real code still cannot spend it. The count
--  is of failures only, so somebody typing their own code correctly is never
--  affected however often they do it, and the window rolls, so a lockout is
--  an hour and not forever.
--
--  Keyed on auth.uid(), because Postgres cannot see the caller's IP from
--  PostgREST. That is only worth having because the cheap way to get a fresh
--  uid — signing in anonymously — is itself behind a CAPTCHA. The two
--  together are the fence; either one alone is a gate.
--
--  THE PART THAT IS NOT OBVIOUS
--  restore_profile() used to raise BAD_CODE for a code that matched nothing.
--  It now returns ZERO ROWS. That is not tidiness: PostgREST runs one call as
--  one transaction, so the raise rolled back the row recording the failure
--  that caused it. The counter counted to zero forever and the lock never
--  closed, while the app looked exactly the same from outside — the caller
--  gets the same refusal either way. supabase/test/guessing.sql section 2 is
--  the check that found it.
--
--  A return type cannot be changed by `create or replace`, and this channel
--  will not run a DROP, so the old one-row version is moved into the
--  `retired` schema in the same transaction: PostgREST does not look there,
--  nothing can call it, and one ALTER puts it back. Both happen together, so
--  there is no instant where both are callable and none where neither is.
--
--  ORDER OF DEPLOY: this file first, the app second. An app that has not
--  updated reads the empty answer as "no profile has that code", which is
--  what a wrong code means anyway — so the gap is harmless in that
--  direction, and the other way round would leave a real refusal looking
--  like a crash.
-- ======================================================================
begin;
set local check_function_bodies = off;

-- --------------------------------------------- somewhere to park the old ---
-- Not exposed to PostgREST and no rights for anybody, so what lands here is
-- unreachable from an app while staying recoverable with one more ALTER.
create schema if not exists retired;
revoke all on schema retired from public;
"""

RETIRE = """
-- ------------------------------- the one-row restore_profile, retired ---
-- Matched on `returns public.profiles` and NOT on the argument list, because
-- the new version takes the same single `p_code text`. Filtering on the name
-- alone would park the new function on a second run of this file.
do $mv$
declare r record; alias text;
begin
  for r in
    select p.oid as id, p.oid::regprocedure as sig, p.proname as nom
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'restore_profile'
      and p.proretset = false
      and pg_get_function_identity_arguments(p.oid) = 'p_code text'
  loop
    begin
      execute format('alter function %s set schema retired', r.sig);
    exception when duplicate_function then
      -- A copy is already parked, so the obvious name is taken. Park this one
      -- under its own rather than leave it visible: a visible twin is what
      -- makes every call from an app that has not updated ambiguous.
      alias := r.nom || '_' || r.id::text;
      execute format('alter function %s rename to %I', r.sig, alias);
      execute format('alter function public.%I(%s) set schema retired',
                     alias, pg_get_function_identity_arguments(r.id));
    end;
    raise notice 'retired %', r.sig;
  end loop;
end $mv$;
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    parts.append("-- ----------------------------------------------- restore_tries ---")
    parts.append(lift(schema, "table", "restore_tries"))
    parts.append("create index if not exists restore_tries_idx"
                 "\n  on public.restore_tries (user_id, tried_at desc);\n")
    parts.append(RETIRE)
    parts.append("-- --------------------------------------------- restore_profile ---")
    parts.append(lift(schema, "function", "restore_profile") + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, ("restore_profile",)))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
