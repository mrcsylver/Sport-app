#!/usr/bin/env python3
"""Write supabase/rest-day.sql from schema.sql.

A rest day belongs to a LEAGUE, and a person can be in several. log_workout()
writes one row per league, the rest rule raised from the insert trigger, and a
raise from any one of those rows takes the whole statement down — so somebody
in two leagues could not log anything at all while ONE of them was resting,
including into the league that was open.

The rule is split in two: rest_day_block() answers "will this league take it",
and rest_day_check() is that answer as a raise, for the triggers. log_workout()
filters the fan-out on the question and only raises when EVERY league refuses,
which keeps the message exactly what it has always been for somebody in one
league.

Create-only: every signature is unchanged, so nothing has to be dropped.

Usage:  python3 tools/build_restday_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "rest-day.sql")

OBJECTS = ["rest_day_block", "rest_day_check", "log_workout"]
WANTED = tuple(OBJECTS)

HEAD = """-- ======================================================================
--  IRON LEAGUE — a rest day in one league no longer shuts the others
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. NOTHING LOGGED IS TOUCHED and no
--  points are rewritten.
--
--  GENERATED by tools/build_restday_migration.py, which lifts all three
--  functions below out of supabase/schema.sql. Edit there and re-run it,
--  never here.
--
--  THE BUG
--  A rest day belongs to a league, and a person can be in several.
--  log_workout() writes one row per league the person is in, and the rest
--  rule raised from the insert trigger. A raise from any one of those rows
--  aborts the whole statement — so while ONE league was resting, somebody in
--  two could not log anything at all, and the league that was open lost the
--  entry too. One league closing its own Sunday should close that league, not
--  the person's day.
--
--  THE FIX
--  The rule is now a question before it is a rule:
--
--    rest_day_block()  why this league will not take this entry, or null
--    rest_day_check()  the same answer as a raise, for the triggers
--
--  log_workout() filters the fan-out on the question, so the leagues that are
--  open score the entry and the resting ones sit it out. It raises only when
--  EVERY league refuses — with the reason the league on screen gives, which
--  keeps the message exactly what it has always been for somebody in one
--  league. It also hands back a row from whichever league did take it, so the
--  app still has a points figure to show when the screen you logged from is
--  the one resting.
--
--  The triggers still call rest_day_check(), so a row written directly — an
--  edit, or anything not coming through the RPC — is refused exactly as
--  before. The one-recovery-a-day rule and the one-session cap on a stretch
--  are per league and unchanged.
-- ======================================================================
begin;
set local check_function_bodies = off;
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, WANTED))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
