#!/usr/bin/env python3
"""Write supabase/player-card.sql from schema.sql.

Tapping somebody's face on the board opens who they are. Create-only:
one column, four functions, nothing changes shape and nothing is dropped.

WHY A FUNCTION AND NOT A WIDER LEADERBOARD. A board is polled every 25
seconds by everybody with the app open and carries a row per member, so a
bio on it would be paid for by every member of every league on every poll.
A card is read once, when a finger lands on a face.

And `profiles` is readable only for your own row -- deliberately, since that
row carries a restore code -- so a card has to be something that CHOOSES
what it returns. player_card() returns no restore code, no bodyweight and no
account id, and its WHERE clause is what stops it being a way to read
strangers.

Usage:  python3 tools/build_card_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "player-card.sql")

OBJECTS = ["set_bio", "player_card", "admin_bios", "admin_clear_bio"]

HEAD = """-- ======================================================================
--  IRON LEAGUE — who somebody is, when you tap their face
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. Create-only: one column and four
--  functions, nothing changes shape, nothing is dropped, NOTHING LOGGED IS
--  TOUCHED and no points move.
--
--  GENERATED by tools/build_card_migration.py, which lifts the functions
--  below out of supabase/schema.sql. Edit there and re-run it, never here.
--
--  WHY
--  Tapping a NAME opens that person's week, which is what you want when you
--  are reading a board. Tapping their FACE opens who they are, which is what
--  you want when somebody you do not recognise is above you -- and on a
--  campus, that is most of them.
--
--  WHAT IT ADDS
--  · profiles.bio -- one line, 140 characters, written by the person.
--  · set_bio(), which trims it and bounds it server-side rather than
--    trusting a client, and stores an empty one as null.
--  · player_card(), the card itself.
--  · admin_bios() and admin_clear_bio(), because a bio is the only free text
--    in this app that strangers read, and "the admin can delete the whole
--    account" is not a proportionate answer to a rude sentence.
--
--  THE PART THAT IS NOT OBVIOUS
--  This is a FUNCTION and not a wider league_leaderboard(), for two reasons.
--  A board is polled every 25 seconds by everybody with the app open and
--  carries a row per member, so a bio on it would be paid for by every
--  member of every league on every poll; a card is read once, when a finger
--  lands on a face.
--
--  And `profiles` is readable only for your own row since
--  shut-the-side-door.sql -- deliberately, because that row carries a
--  restore code. So a card cannot be a SELECT; it has to be something that
--  CHOOSES what it returns. player_card() returns no restore code, no
--  bodyweight and no account id, and its WHERE clause is what stops it being
--  a way to read strangers: you see somebody you share a league with, or you
--  see nothing.
--
--  ORDER OF DEPLOY: this file first, the app second. An app that has not
--  updated never calls any of it.
-- ======================================================================
begin;
set local check_function_bodies = off;

-- ------------------------------------------------------- the column ---
alter table public.profiles add column if not exists bio text;
alter table public.profiles drop constraint if exists profiles_bio_len;
alter table public.profiles add constraint profiles_bio_len
  check (bio is null or char_length(bio) <= 140);
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, tuple(OBJECTS)))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
