#!/usr/bin/env python3
"""Write supabase/launch-gate.sql from schema.sql.

Two things, because they are the same thing from two ends.

HISTORY OUTLIVES A MEMBERSHIP. weekly_history inner-joined league_members
purely to fetch joined_at for the tie-break, so anybody who left — or was
taken out to free a seat — stopped having won the weeks they won: the hall of
fame re-ranked, crowns moved, the season table reshuffled and the cup
reseeded, retroactively. league_roster() is the fix: the people in a league
now, plus anybody who ever logged into it, with joined_at falling back to
their first workout.

A SEAT CAN BE FREED WITHOUT DELETING ANYBODY. profiles.dormant_at parks an
account: it stops counting against the cap and drops off live boards, and
everything it logged stays exactly where it is. app_settings.user_cap is the
cap itself, a row rather than a constant so it can be raised from the control
room the moment the database shrugs.

Usage:  python3 tools/build_launchgate_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "launch-gate.sql")

# A return type cannot be widened in place. league_wins and league_season
# gained `member` so a board can show somebody who earned their place and then
# left; admin_players gained dormant_at.
RESHAPED = [
    ("league_wins", "p_league uuid"),
    ("league_season", "p_league uuid, p_season int"),
    ("admin_players", ""),
]

# league_roster first: weekly_history reads it, and four more read that.
OBJECTS = ["league_roster", "weekly_history", "league_wins", "league_season",
           "league_leaderboard", "league_streaks", "my_leagues",
           "league_preview", "enforce_league_capacity",
           "signup_state", "app_is_full", "create_profile", "restore_profile",
           "wake_me", "admin_overview", "admin_set_cap", "admin_set_dormant",
           "admin_players"]

WANTED = tuple(OBJECTS)

HEAD = """-- ======================================================================
--  IRON LEAGUE — a seat you can free, and a past nobody can edit
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. NOTHING LOGGED IS TOUCHED and no
--  points are rewritten.
--
--  GENERATED by tools/build_launchgate_migration.py, which lifts every
--  function below out of supabase/schema.sql. Edit there and re-run it,
--  never here.
--
--  WHY, PART ONE: HISTORY HAS TO OUTLIVE A MEMBERSHIP
--  weekly_history inner-joined league_members, purely to fetch joined_at for
--  the tie-break. The effect nobody noticed: anybody who LEFT a league
--  stopped having won the weeks they won. The hall of fame re-ranked, crowns
--  moved to the runner-up, the season table reshuffled and the cup reseeded —
--  all retroactively, all silently. A roster is a fact about now; a finished
--  week is a fact about then, and leaving must not be able to edit it.
--
--  league_roster() replaces that join: the people in a league now, PLUS
--  anybody who ever logged into it, with joined_at falling back to their
--  first workout there once the membership row is gone. league_wins and
--  league_season now read it too, and both gained a `member` column so a
--  board can show somebody who earned their crowns and then left, marked as
--  no longer in the league. Somebody who left without ever scoring has no
--  history to show and falls out on their own.
--
--  WHY, PART TWO: A SEAT YOU CAN FREE WITHOUT DELETING ANYBODY
--  profiles.dormant_at parks an account. It is NOT a deletion:
--
--    · everything they logged stays, and still counts for everyone else
--    · every week they won stays theirs, in the hall of fame and the crowns
--    · their leagues still list them, so putting them back is one switch
--    · they stop counting against the cap, and drop off live boards
--
--  That last line is what frees the seat — globally, and in each league's 36.
--
--  app_settings.user_cap is the cap. A row, not a constant, so it can be
--  raised from the control room at three in the morning. null means no cap,
--  which is where it starts, so applying this file changes nothing until
--  somebody sets a number.
--
--  Coming back to a parked account needs a free seat, same as anybody else
--  arriving: restore_profile() and wake_me() both raise APP_FULL rather than
--  letting the app quietly go over. Nothing is lost by waiting.
-- ======================================================================
begin;
set local check_function_bodies = off;

-- ------------------------------------------------- the cap, as a row ---
create table if not exists public.app_settings (
  only_row   boolean primary key default true check (only_row),
  user_cap   int check (user_cap is null or user_cap >= 0),
  updated_at timestamptz not null default now()
);
insert into public.app_settings (only_row, user_cap) values (true, null)
  on conflict (only_row) do nothing;
alter table public.app_settings enable row level security;
drop policy if exists app_settings_read on public.app_settings;
create policy app_settings_read on public.app_settings for select
  to anon, authenticated using (true);

-- --------------------------------------------- parked, not deleted ---
alter table public.profiles add column if not exists dormant_at timestamptz;
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    parts.append("-- --------------------------------------- shapes that changed ---")
    for name, args in RESHAPED:
        parts.append("drop function if exists public.%s(%s) cascade;" % (name, args))
    parts.append("")
    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, WANTED))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
