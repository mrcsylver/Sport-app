#!/usr/bin/env python3
"""Write supabase/faster-board.sql from schema.sql.

league_leaderboard() read life_scored_all(), which scans EVERY workout ever
logged by anybody, scores the lot, and then throws away all but the league's
members. That happens on every poll, every 25 seconds, for every person with
the app open -- so the cost per poll grows with the app and the number of
polls grows with the app, and the product is what falls over first.

Measured on a database seeded to 290 people with a year of training each
(49,300 workouts): 357 ms per poll, the sort spilling to disk, with every
other part of the board costing 2-11 ms. The same board through
life_scored_in(): 38 ms.

Create-only. Nothing changes shape, so it can go in over the API.

Usage:  python3 tools/build_board_migration.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sqllift import lift, grants                                   # noqa: E402

SCHEMA = os.path.join(ROOT, "supabase", "schema.sql")
OUT = os.path.join(ROOT, "supabase", "faster-board.sql")

OBJECTS = ["life_scored_in", "league_leaderboard"]
WANTED = tuple(OBJECTS)

HEAD = """-- ======================================================================
--  IRON LEAGUE — the leaderboard stops re-scoring the whole app
--
--  Paste the whole file into the Supabase SQL editor and press RUN, or apply
--  it over the API. Safe to run twice. Create-only: nothing changes shape,
--  nothing is dropped, NOTHING LOGGED IS TOUCHED and no points move. Every
--  number on every board is identical before and after.
--
--  GENERATED by tools/build_board_migration.py, which lifts both functions
--  below out of supabase/schema.sql. Edit there and re-run it, never here.
--
--  WHY
--  league_leaderboard() read life_scored_all(). That function has no WHERE
--  clause: it reads every workout ever logged, by anybody, in any league,
--  sorts the lot to dedupe the multi-league fan-out, and scores all of it.
--  The board then threw away every row but its own members'.
--
--  So one poll re-scored the entire app's history. The app polls every 25
--  seconds, per person with it open. Cost per poll grows with the app; polls
--  per minute grow with the app; the product of the two is what runs out of
--  CPU first -- well before the database runs out of room.
--
--  MEASURED, on a database seeded to 290 people with a year of training each
--  (49,300 workouts, 13 MB):
--
--    life_scored_all()        357 ms   <- the whole board, essentially
--    week_scored()              2.7 ms
--    week_combo_bonus()         2.7 ms
--    week_bounty_points()      11 ms
--
--  and the sort spilled to disk (654 temp blocks) on every single call.
--
--  THE FIX
--  life_scored_in(p_league) narrows the PEOPLE to that league's members --
--  never the leagues. A lifetime still counts what somebody logged
--  everywhere, which is why the filter is on profile_id and the
--  `distinct on (group_id)` dedup is untouched. The same board now costs
--  38 ms, and it scales with how many people are in the league rather than
--  with how big the app has become.
--
--  Proven identical to life_scored_all() for every member of every league in
--  supabase/test/board.sql. life_scored_all() stays: the control room still
--  wants everybody at once, and that page is read by one person, rarely.
--
--  A covering index on (group_id, league_id) was tried first and rejected:
--  at this scale it changed 370 ms into 345 ms and cost 4.4 MB. The problem
--  was never the dedup -- it was scoring 290 people to show 29.
-- ======================================================================
begin;
set local check_function_bodies = off;
"""

TAIL = """
commit;
"""


def main():
    schema = open(SCHEMA, encoding="utf-8").read()
    parts = [HEAD]
    for name in OBJECTS:
        parts.append("-- " + ("-" * (70 - len(name))) + " " + name + " ---")
        parts.append(lift(schema, "function", name) + "\n")
    parts.append("-- -------------------------------------------------------- grants ---")
    parts.append(grants(schema, WANTED))
    parts.append(TAIL)
    body = "\n".join(parts) + "\n"
    open(OUT, "w", encoding="utf-8").write(body)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(body.splitlines())))


if __name__ == "__main__":
    main()
