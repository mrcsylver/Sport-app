  function rateLabel(mode, rate, key) {
    function n(x) { return String(Math.round(x * 100) / 100); }
    if (mode === 'minutes') return n(rate * 60) + ' pts / hour';
    if (mode === 'seconds') {
      return rate >= 1 ? n(rate) + ' pts / sec' : '1 pt / ' + n(1 / rate) + ' sec';
    }
    if (mode === 'km')   return n(rate) + ' pts / km';
    if (mode === 'flat') return n(rate) + ' pts / session';
    if (key === 'sprints') return n(rate) + ' pts / sprint';
    return (rate === 1 ? '1 pt' : n(rate) + ' pts') + ' / rep';
  }

